-- Scanner diagnostics log — field-side evidence for scan bugs.
-- The Flutter app writes local-first (SQLite) then flushes batches here.

create table if not exists public.scan_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  screen text not null,
  event text not null,
  uid text,
  registration text,
  document_no text,
  detail jsonb
);

alter table public.scan_logs enable row level security;

-- The app authenticates with the operational master account.
create policy "scan_logs_insert_authenticated"
  on public.scan_logs for insert
  to authenticated
  with check (true);

create policy "scan_logs_select_authenticated"
  on public.scan_logs for select
  to authenticated
  using (true);

create index if not exists scan_logs_created_at_idx
  on public.scan_logs (created_at desc);
